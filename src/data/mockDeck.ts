function slug(value: string) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')
}

function makeDeck(seed: DeckSeed): KnowledgeDeck {
  const cards: KnowledgeCard[] = seed.terms.map(([titleEn, titleZh, shortEn]) => ({
    id: `${seed.id}-${slug(titleEn)}`,
    titleZh,
    titleEn,
    shortEn: shortEn ?? titleEn,
    descriptionZh: `探索「${titleZh}」的定义、运行机制，以及它在${seed.name}中的应用与影响。`,
    category: seed.category,
    tags: [seed.name, titleEn],
    source: 'Knowledge Orbit Catalog',
    importance: 4,
    studyState: 'question',
    createdAt,
  }))

  return {
    id: seed.id,
    name: seed.name,
    language: 'bilingual',
    category: seed.category,
    cards,
    mode: 'creator',
    isBuiltIn: true,
    shareSlug: seed.id,
    createdAt,
    updatedAt: createdAt,
  }
}

export const builtInDecks = deckSeeds.map(makeDeck)
